type RulePlan = {
  group: RuleMigrationGroup;
  severity: "error" | "warning" | "info";
  predicate: string;
  layer: "declared" | "artifact" | "runtime";
  subjectKind:
    | "project"
    | "dependency"
    | "remote"
    | "shared-package"
    | "build"
    | "artifact"
    | "runtime-instance";
  confidenceCeiling: "exact" | "high" | "medium" | "low" | "unknown";
  adapters: readonly string[];
  bundlers: readonly string[];
  confidenceReason: string;
};

