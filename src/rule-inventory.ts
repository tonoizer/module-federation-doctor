function selectorFor(path: string, spec: RulePlan): EvidenceRequirement {
  const predicate =
    path === "config.declared"
      ? "project.moduleFederation"
      : path === "source.scan"
        ? "project.imports"
        : path === "imports.sourceScan"
          ? "imports.sourceScan"
          : path;
  const layer =
    predicate === "runtime.trace"
      ? "runtime"
      : predicate === "project.imports"
        ? "effective"
        : predicate === "federation.graph" ||
            predicate === "project.scope" ||
            predicate === "moduleFederation" ||
            predicate === "project.moduleFederation"
          ? "declared"
          : predicate.startsWith("artifacts.")
            ? "artifact"
            : "effective";
  const subjectKind =
    predicate === "runtime.trace"
      ? "runtime-instance"
      : predicate.startsWith("artifacts.")
        ? "artifact"
        : spec.subjectKind;
  return {
    predicate,
    layer,
    subjectKind,
    minimumConfidence: spec.confidenceCeiling,
    minimumCompleteness: "complete",
  };
}

function requirementFor(id: string, spec: RulePlan): EvidenceRequirement {
  const reads = evidenceReadsByRule[id];
  if (!reads) throw new Error(`Evidence prerequisites are missing for ${id}`);
  if (id === "config/duplicate-plugin-registration") {
    return {
      allOf: [
        selectorFor("project.scope", spec),
        {
          anyOf: [
            selectorFor("bundler.moduleFederationPluginCount", spec),
            selectorFor("bundler.federationInstances", spec),
          ],
        },
      ],
    };
  }
  const optionalPluginFacts: Record<string, readonly string[]> = {
    "doctor/partial-analysis": ["moduleFederation"],
    "vite/host-init-inject-ssr": ["builds"],
    "vite/ssr-nitro-externals": ["builds"],
    "vite/manual-chunks-conflict": ["bundler.viteConfig"],
    "vite/alias-share-bypass": ["bundler.viteConfig"],
    "vite/server-origin": ["bundler.viteConfig"],
    "vite/remote-hmr-dev": ["builds"],
    "config/transform-import-share-conflict": ["bundler.transformImportLibraries"],
    "config/rsbuild-mf-api-generation": ["canonicalConfig", "dependencies.installed"],
  };
  const optional = optionalPluginFacts[id];
  if (optional) {
    return {
      allOf: reads
        .filter((path) => !optional.includes(path))
        .map((path) => selectorFor(path, spec)),
    };
  }
  return { allOf: reads.map((path) => selectorFor(path, spec)) };
}

function applicabilityFor(spec: RulePlan): RuleApplicability {
  return {
    adapters: spec.adapters.map((name) => ({ name })),
    bundlers: spec.bundlers.map((name) => ({ name })),
  };
}

function inventoryStatusFor(id: string): RuleMigrationStatus {
  if (COMPATIBILITY_EXCEPTION_IDS.has(id)) return "legacy";
  if (MIGRATED_RULE_IDS.has(id)) return "migrated";
  throw new Error(`Built-in ${id} is neither migrated nor documented as a compatibility exception`);
}

function migrationNoteFor(id: string, spec: RulePlan): string {
  if (COMPATIBILITY_EXCEPTION_IDS.has(id)) {
    const exception = RULE_COMPATIBILITY_EXCEPTIONS.find((entry) => entry.id === id);
    if (!exception) throw new Error(`Missing compatibility exception metadata for ${id}`);
    return `Group ${spec.group}; compatibility-only exception (${exception.reason}). ${exception.deprecationPlan}`;
  }
  return `Group ${spec.group}; ${spec.confidenceReason} Migrated through the evidence-aware rollout bridge with golden V1 parity in shadow and v2-compat modes.`;
}

/** Machine-readable migration ledger for every current built-in. */
export const ruleInventory: readonly RuleInventoryEntry[] = ids.map((id) => {
  const spec = plans[id];
  const guidance = ruleGuidance[id];
  const evidenceReads = evidenceReadsByRule[id];
  if (!spec || !guidance || !evidenceReads)
    throw new Error(`Rule inventory is incomplete for ${id}`);
  return {
    id,
    version: "1",
    owner: { name: "MFDoctor maintainers" },
    remediation: {
      summary: guidance.impact,
      documentation: `/rules/${id}`,
      fix: guidance.fix,
    },
    prerequisites: requirementFor(id, spec),
    applicability: applicabilityFor(spec),
    confidenceCeiling: spec.confidenceCeiling,
    defaultSeverity: spec.severity,
    group: spec.group,
    status: inventoryStatusFor(id),
    evidenceReads,
    migrationNote: migrationNoteFor(id, spec),
  };
});

